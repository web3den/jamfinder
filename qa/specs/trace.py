"""Traceability: every requirement to the tests that verify it, run now, with the result.

    python -m qa.specs.trace          # writes qa/specs/TRACEABILITY.md; exit code 1 if an accepted requirement fails

Status per requirement:
  VERIFIED       every linked test and check passes
  OPEN           a linked test is a known, documented failure (a strict xfail): the requirement is not met yet
  FAILED         a linked test or check fails
  NOT VERIFIED   nothing is linked, or a linked test does not exist
Also listed: tests that verify no requirement (they may test something nobody asked for, or a requirement is
missing from the list).
"""
import subprocess
import sys
import tempfile
import tomllib
import xml.etree.ElementTree as ET
from pathlib import Path

from qa.harness import gate

ROOT = Path(__file__).resolve().parents[2]
SPECS = ROOT / "qa" / "specs" / "requirements.toml"


def run_tests(files):
    """Run pytest on the files; per test id ("file::name", parameters stripped) the worst outcome seen."""
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "junit.xml"
        subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", f"--junitxml={report}",
                        "-o", "junit_family=xunit1", *sorted(files)], cwd=ROOT, capture_output=True, text=True)
        cases = list(ET.parse(report).getroot().iter("testcase"))
    rank = {"passed": 0, "xfail": 1, "failed": 2}
    out = {}
    for c in cases:
        tid = f"{c.get('file')}::{c.get('name').split('[')[0]}"
        kids = {k.tag: k for k in c}
        if "failure" in kids or "error" in kids:
            res = "failed"
        elif "skipped" in kids:
            res = "xfail" if "xfail" in (kids["skipped"].get("type", "") + kids["skipped"].get("message", "")) \
                else "failed"                        # a plain skip does not verify anything
        else:
            res = "passed"
        if rank[res] >= rank.get(out.get(tid), -1):
            out[tid] = res
    return out


def gate_check(name):
    policy = tomllib.loads(gate.POLICY.read_text())
    files = gate.git_files()
    check = {"secrets": lambda: gate.check_secrets(files), "architecture": lambda: gate.check_architecture(files, policy),
             "skips": lambda: gate.check_skips(files, policy), "protected": lambda: gate.check_protected(policy)}[name]
    return "passed" if not check() else "failed"


def main():
    reqs = tomllib.loads(SPECS.read_text())["requirement"]
    links = {link for r in reqs for link in r["verified_by"]}
    files = {link.split("::")[0] for link in links if not link.startswith("gate:")}
    results = run_tests(files | {"tests", "qa"})        # everything, so unlinked tests can be listed too

    def outcome(link):
        if link.startswith("gate:"):
            return gate_check(link[5:])
        if "::" in link:
            return results.get(link, "missing")
        mine = [v for k, v in results.items() if k.startswith(link + "::")]
        return "missing" if not mine else "failed" if "failed" in mine else "passed"

    md = ["# Traceability: requirements to verification", "",
          "Generated by `python -m qa.specs.trace` from `qa/specs/requirements.toml`.", "",
          "| requirement | status | method | requirement text | verified by |", "|---|---|---|---|---|"]
    bad = 0
    for r in reqs:
        got = {link: outcome(link) for link in r["verified_by"]}
        status = ("NOT VERIFIED" if not got or "missing" in got.values() else "FAILED" if "failed" in got.values()
                  else "OPEN" if "xfail" in got.values() else "VERIFIED")
        bad += status in ("FAILED", "NOT VERIFIED") and r["status"] == "accepted"
        refs = "<br>".join(f"`{link.split('/')[-1]}` {v}" for link, v in got.items())
        label = f"{r['id']}" + (" (proposed)" if r["status"] == "proposed" else "")
        md.append(f"| {label} | **{status}** | {r['method']} | {r['text']} | {refs} |")
    linked = {k for k in results for link in links if not link.startswith("gate:")
              and (k == link or k.startswith(link + "::"))}
    orphans = sorted(k for k in results if k not in linked)
    md += ["", f"Tests run: {len(results)}. Linked to a requirement: {len(linked)}. Not linked to any: {len(orphans)} "
               "(tests of internals, or a requirement not yet written down):", ""]
    md += [f"- `{k}`" for k in orphans]
    (ROOT / "qa" / "specs" / "TRACEABILITY.md").write_text("\n".join(md) + "\n")
    print("\n".join(md[:5 + len(reqs)]))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
