def rule_v32(cands, nulls, residual):
    """Evaluate reporting rule v3.2.

    Args:
        cands: list of (score, east, north, dt), best first. Only score matters.
        nulls: list of dicts with keys:
            - kind: 'flip' or 'shift'
            - verdict: 'one', 'ambiguous', or 'nothing'
            - best: best score for that null
            - optional frac: share of aircraft-seconds kept
        residual: largest score left after blanking the best spot's predicted echo lines

    Returns:
        dict with booleans a_flip, b, c, d and v32 ('one' or 'nothing').
    """

    # (a') spectrum-flip null is "nothing"; if no flip null exists, false.
    flip_nulls = [n for n in nulls if n.get("kind") == "flip"]
    a_flip = any(n.get("verdict") == "nothing" for n in flip_nulls) if flip_nulls else False

    # Non-degenerate nulls: those without frac, or with frac >= 0.5
    nondegenerate_nulls = [
        n for n in nulls
        if "frac" not in n or n.get("frac") is None or n.get("frac") >= 0.5
    ]

    if nondegenerate_nulls:
        largest_null_best = max(n.get("best", float("-inf")) for n in nondegenerate_nulls)
        b = cands[0][0] >= 3 * largest_null_best if cands else False
        c = residual < largest_null_best
    else:
        # Without any non-degenerate null, (b) and (c) are false.
        b = False
        c = False

    # (d) runner-up < 0.75 x best
    if len(cands) >= 2:
        best = cands[0][0]
        runner_up = cands[1][0]
        d = runner_up < 0.75 * best
    else:
        d = False

    v32 = "one" if (a_flip and b and c and d) else "nothing"
    return {"a_flip": a_flip, "b": b, "c": c, "d": d, "v32": v32}
