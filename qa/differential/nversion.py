"""N-version programming: a second implementation of the reporting rule, written by a model from the written
definition alone (it never sees jf/rules.py), then compared with the real one on generated inputs.

    python -m qa.differential.nversion      # writes nversion_generated.py and NVERSION.md

Where the two disagree, one of three things is true: the code is wrong, the second version is wrong, or the
written definition allows both readings. The third is the valuable one: an ambiguity in the specification,
found before it bites. Hypothesis shrinks every disagreement to the smallest input that shows it.
"""
import json
import sys

from hypothesis import HealthCheck, find, settings
from hypothesis.errors import NoSuchExample

from jf import rules
from qa.core import llm
from qa.core.sandbox import COPIED, ROOT, Workspace
from qa.properties.strategies import rule_input

SPEC = """The reporting rule v3.2. Inputs:
  cands     the search's candidates, best first: a list of (score, east, north, dt); only the scores matter
  nulls     control searches ("nulls"): dicts with "kind" ("flip" or "shift"), "verdict" ("one", "ambiguous" or
            "nothing"), the best score as "best", and optionally "frac" (share of aircraft-seconds kept)
  residual  the largest score left after blanking the best spot's predicted echo lines
A null is degenerate when its shifted tracks keep less than half of the aircraft-seconds inside the recording
(its row carries frac < 0.5). A row without frac counts as non-degenerate. Degenerate nulls take no part.
Conditions:
  (a') the spectrum-flip null is "nothing" (no flip null -> false)
  (b)  best >= 3 x the largest best score over the non-degenerate nulls
  (c)  the residual < that largest null best
  (d)  the runner-up < 0.75 x best
Without any non-degenerate null, (b) and (c) are false.
v3.2 reports "one" if (a'), (b), (c) and (d) all hold, else "nothing"."""

SCHEMA = {"type": "object", "additionalProperties": False, "required": ["code"],
          "properties": {"code": {"type": "string"}}}
CONDITIONS = ("a_flip", "b", "c", "d", "v32")


def generate():
    code = llm.ask("generator", "You implement specifications exactly as written, in plain Python.",
                   f"{SPEC}\n\nWrite a function rule_v32(cands, nulls, residual) that returns a dict with the keys "
                   f"a_flip, b, c, d (booleans) and v32 ('one' or 'nothing'). Standard library only.",
                   SCHEMA, tag="nversion")["code"]
    header = ('"""Rule v3.2, written by a model from the definition in qa/differential/nversion.py (SPEC) without '
              'seeing jf/rules.py.\nGenerated by `python -m qa.differential.nversion`."""\n')
    (ROOT / "qa" / "differential" / "nversion_generated.py").write_text(header + code.strip() + "\n")
    return code


def both(x, second):
    real = rules.evaluate(x["cands"], x["nulls"], x["residual"], x["support"])
    other = second(x["cands"], x["nulls"], x["residual"])
    mine = {k: real["conditions"][k] for k in CONDITIONS[:4]} | {"v32": real["v32"]}
    return mine, {k: other[k] for k in CONDITIONS}


def disagreements(second):
    """Per output, the smallest input on which the two versions disagree (None: none in 5000 tries)."""
    out = {}
    for key in CONDITIONS:
        try:
            out[key] = find(rule_input(), lambda x: (lambda a, b: a[key] != b[key])(*both(x, second)),
                            settings=settings(max_examples=5000, database=None, derandomize=True,
                                              suppress_health_check=list(HealthCheck)))
        except NoSuchExample:
            out[key] = None
    return out


def compare():
    """Runs inside the sandbox: the model's code is imported only there."""
    from qa.differential import nversion_generated
    found = disagreements(nversion_generated.rule_v32)
    rows = {}
    for key, x in found.items():
        if x is not None:
            a, b = both(x, nversion_generated.rule_v32)
            rows[key] = dict(input={k: v for k, v in x.items() if k != "support"}, real=a[key], second=b[key])
    print("RESULT " + json.dumps(rows, default=str))


def main():
    generate()
    with Workspace(files=COPIED + ("qa/differential", "qa/properties")) as ws:
        code, out, isolation = ws.run(["-m", "qa.differential.nversion", "--compare"], timeout=600)
    line = next((x for x in out.splitlines() if x.startswith("RESULT ")), None)
    if line is None:
        sys.exit("the comparison did not finish:\n" + out[-2000:])
    found = json.loads(line[7:])
    md = ["# N-version programming: the reporting rule written twice", "",
          f"Second version: {llm.MODELS['generator']}, from the written definition only "
          "(`qa/differential/nversion_generated.py`). Compared with `jf/rules.py` on generated inputs.", "",
          "| output | agreement | smallest input where they differ | jf/rules.py | second version |",
          "|---|---|---|---|---|"]
    for key in CONDITIONS:
        if key not in found:
            md.append(f"| {key} | same on 5000 inputs | | | |")
        else:
            d = found[key]
            md.append(f"| {key} | **differs** | `{d['input']}` | {d['real']} | {d['second']} |")
    (ROOT / "qa" / "differential" / "NVERSION.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    compare() if "--compare" in sys.argv else main()
